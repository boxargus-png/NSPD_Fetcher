        self._validate_delay_settings()
        for widget in (self.treeWidget, self.tabWidgetQueryMode, self.groupBoxCRS, self.groupBoxSettings):
            widget.setEnabled(not busy)
        self.btnFetch.setText("Загрузка…" if busy else "Загрузить данные")
