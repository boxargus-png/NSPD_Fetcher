    def _validate_delay_settings(self):
        minimum, maximum = self.spinDelayMin.value(), self.spinDelayMax.value()
        if minimum > maximum:
            self.labelDelayWarning.setText("Минимальное значение не может быть больше максимального.")
            self.labelDelayWarning.setStyleSheet("color: red;")
        elif minimum <= 1 or maximum <= 1:
            self.labelDelayWarning.setText("Внимание! При задержке менее 2 секунд существует высокий риск блокировки IP со стороны НСПД.")
